/// 超过 0x7FFF 的偏移按 % 0x7FFF 回绕（0x7FFF 本身不回绕）。
fn wrap(off: u64) -> u64 {
    if off > 0x7FFF {
        off % 0x7FFF
    } else {
        off
    }
}

